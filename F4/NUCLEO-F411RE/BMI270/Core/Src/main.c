void BMI270_I2C_init()
{
	HAL_GPIO_WritePin(SDO_GPIO_Port, SDO_Pin, GPIO_PIN_RESET);
	/*-[ I2C Bus Scanning ]-*/
	uint8_t i = 0, ret;
	printf("%s", StartMSG);
	printf("%s", Space);
    for (i = 1; i < 128; ++i)
    {
        if (i % 16 == 0)
        {
        	printf("%s", NewLine);
        }
        ret = HAL_I2C_IsDeviceReady(&hi2c1, (uint16_t)(i<<1), 3, 5);
        if (ret != HAL_OK) /* No ACK Received At That Address */
        {
        	printf("%s", Space);
        }
        else if(ret == HAL_OK)
        {
            printf("0x%X", i);
            if (i == 0x68 || i == 0x69) // MPU-6050, BMI270
            {
          	  i2c_address = i;
            }
            if (i == 0x53 || i == 0x1D) // ADXL345
            {
          	  i2c_address = i;
            }
        }
    }
    printf("%s", EndMSG);
    /*--[ Scanning Done ]--*/
    uint8_t chip_address;
    I2C1_byteRead(i2c_address, 0x00, &chip_address);
//    HAL_I2C_Mem_Read(&hi2c1, i2c_address << 1, 0x00, 1, &chip_address, 1, 100);
    printf("chip id: 0x%X\r\n", chip_address);

    // Soft reset
#define BMI_ADDRESS_RESET 		0x7E
#define BMI_VALUE_SOFT_RESET 	0xB6
    temp[0] = BMI_VALUE_SOFT_RESET;
    I2C1_byteWrite(i2c_address, BMI_ADDRESS_RESET, temp);
    HAL_Delay(10);

    // Write config file
#define BMI_ADDRESS_PWR_CONFIG 	0x7C
#define BMI_ADDRESS_INIT_CTRL 	0x59
#define BMI_ADDRESS_INIT_DATA 	0x5E
    temp[0] = 0x00; // value to disbale pwr save
    I2C1_byteWrite(i2c_address, BMI_ADDRESS_PWR_CONFIG, temp);
    HAL_Delay(1);
    // Prepare for loading
    I2C1_byteWrite(i2c_address, BMI_ADDRESS_INIT_CTRL, temp);
	// Write the whole thing
	I2C1_burstWrite(i2c_address, BMI_ADDRESS_INIT_DATA, 8192, bmi270_Config_File);
	// Finish loading
	temp[0] = 0x01;
	I2C1_byteWrite(i2c_address, BMI_ADDRESS_INIT_CTRL, temp);
	HAL_Delay(20);

	// Verify it worked
#define BMI_ADDRESS_INIT_STATUS 0x21
	I2C1_byteRead(i2c_address, BMI_ADDRESS_INIT_STATUS, temp);
	if (temp[0] != 0x01)
	{
		printf("ERROR CONFIG\r\n");
	}

	// Set normal power mode
#define BMI_ADDRESS_PWR_CTRL 	0x7D
#define BMI_VALUE_PWR_CTRL		0x0E
	temp[0] = BMI_VALUE_PWR_CTRL;
	I2C1_byteWrite(i2c_address, BMI_ADDRESS_PWR_CTRL, temp);

#define BMI_ADDRESS_ACC_CONF 	0x40
#define BMI_ADDRESS_GYR_CONF 	0x42
#define BMI_VALUE_ACC_CONF 		0xA8
#define BMI_VALUE_GYR_CONF 		0xA9
	temp[0] = BMI_VALUE_ACC_CONF;
	I2C1_byteWrite(i2c_address, BMI_ADDRESS_ACC_CONF, temp);
	temp[0] = BMI_VALUE_GYR_CONF;
	I2C1_byteWrite(i2c_address, BMI_ADDRESS_GYR_CONF, temp);

#define BMI_VALUE_PWR_CONF_DISABLE 0x02
	temp[0] = BMI_VALUE_PWR_CONF_DISABLE;
	I2C1_byteWrite(i2c_address, BMI_ADDRESS_PWR_CONFIG, temp);

	printf("BMI270 is configured\r\n");
}

