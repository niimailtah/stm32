void SPI1_transmit(uint8_t *data, uint32_t size)
{
    uint32_t i = 0;
    volatile uint8_t temp;

    while (i < size)
    {
        while (!(SPI1->SR & (SPI_SR_TXE))) {}   /* Wait until TXE is set */
        SPI1->DR = data[i];                 /* Write the data to the data register */
        i++;
    }
    while (!(SPI1->SR & (SPI_SR_TXE))) {}       /* Wait until TXE is set */
    while ((SPI1->SR & (SPI_SR_BSY))) {}        /* Wait for BUSY flag to reset */
    temp = SPI1->DR;                        /* Clear OVR flag */
    temp = SPI1->SR;
}

void SPI1_receive(uint8_t *data, uint32_t size)
{
    while (size)
    {
        SPI1->DR = 0;                       /* Send dummy data */
        while (!(SPI1->SR & (SPI_SR_RXNE))) {}  /* Wait for RXNE flag to be set */
        *data++ = (SPI1->DR);               /* Read data from data register */
        size--;
    }
}

